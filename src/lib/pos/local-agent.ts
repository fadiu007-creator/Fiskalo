/**
 * Obtain a fresh server signature for a nonce generated by the paired local Agent,
 * then have the Agent verify and persist it. The browser never supplies a timestamp.
 */
export async function refreshVerifiedPosHeartbeat(
  agentSessionToken: string,
  supabaseAccessToken: string,
  recoveryWorkerUrl: string,
  businessId: string,
  posUuid: string,
): Promise<VerifiedPosHeartbeat> {
  const endpoint = new URL(recoveryWorkerUrl);
  if (endpoint.protocol !== "https:" || endpoint.username || endpoint.password || endpoint.search || endpoint.hash) {
    throw new Error("The ATK recovery Worker must be configured with a trusted HTTPS origin.");
  }
  const challenge = await call<{ nonce: string; expiresInSeconds: number }>(
    "/api/v1/connectivity/challenge",
    agentSessionToken,
    { businessId, posUuid },
  );
  const response = await fetch(new URL("/heartbeat", endpoint.origin), {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: "Bearer " + supabaseAccessToken,
    },
    body: JSON.stringify({ businessId, posUuid, nonce: challenge.nonce }),
    cache: "no-store",
    credentials: "omit",
    referrerPolicy: "no-referrer",
  });
  const signed = await response.json().catch(() => ({})) as {
    issuedAtUnixMs?: number;
    signatureBase64?: string;
    nonce?: string;
    businessId?: string;
    posUuid?: string;
  };
  if (!response.ok || signed.nonce !== challenge.nonce ||
      signed.businessId !== businessId || signed.posUuid !== posUuid ||
      !Number.isSafeInteger(signed.issuedAtUnixMs) || typeof signed.signatureBase64 !== "string") {
    throw new Error("The server did not return a valid signed POS heartbeat.");
  }
  return call<VerifiedPosHeartbeat>(
    "/api/v1/connectivity/heartbeat",
    agentSessionToken,
    {
      nonce: challenge.nonce,
      issuedAtUnixMilliseconds: signed.issuedAtUnixMs,
      signatureBase64: signed.signatureBase64,
    },
  );
}

